using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace SteamEngine.Generators.ThingAndPluginClasses;

internal static class Renderer {
	internal static string GetHintName(TemplatePair pair) {
		var key = $"{pair.NamespaceName}.{pair.Family}.{pair.InstanceName}";
		var builder = new StringBuilder(key.Length + 20);
		foreach (var c in key) {
			builder.Append(char.IsLetterOrDigit(c) ? c : '_');
		}
		builder.Append(".TemplatePairing.g.cs");
		return builder.ToString();
	}

	internal static bool TryRenderPair(TemplatePair pair, out string source) {
		var builder = new StringBuilder();
		AppendFileHeader(builder, pair.NamespaceName);
		RenderDefPartial(builder, pair);
		builder.AppendLine();
		RenderInstancePartial(builder, pair);
		builder.AppendLine("}");
		source = builder.ToString();
		return true;
	}

	private static void AppendFileHeader(StringBuilder builder, string nameSpace) {
		builder.AppendLine("// <auto-generated/>");
		builder.AppendLine("using System;");
		builder.AppendLine("using System.Collections.Generic;");
		builder.AppendLine("using SteamEngine;");
		builder.AppendLine("using SteamEngine.Persistence;");
		builder.AppendLine();
		builder.AppendLine($"namespace {nameSpace} {{");
		builder.AppendLine();
	}

	private static void RenderDefPartial(StringBuilder builder, TemplatePair pair) {
		builder.AppendLine($"\tpublic partial class {pair.DefName} : {pair.DefBaseName} {{");
		AppendDefBootstrap(builder, pair);
		AppendDefConstructor(builder, pair, pair.DefFields);
		AppendDefProperties(builder, pair.DefFields);
		AppendDefCreateImpl(builder, pair);
		builder.AppendLine("\t}");
	}

	private static void AppendDefBootstrap(StringBuilder builder, TemplatePair pair) {
		builder.AppendLine("\t\tpublic static new void Bootstrap() {");
		if (pair.Family == TemplateFamily.Thing) {
			builder.AppendLine($"\t\t\tThingDef.RegisterThingDef(typeof({pair.DefName}), typeof({pair.InstanceName}));");
		} else {
			builder.AppendLine($"\t\t\tPluginDef.RegisterPluginDef(typeof({pair.DefName}), typeof({pair.InstanceName}));");
		}
		builder.AppendLine("\t\t}");
		builder.AppendLine();
	}

	private static void AppendDefConstructor(StringBuilder builder, TemplatePair pair, IReadOnlyCollection<DefFieldSpec> fields) {
		builder.AppendLine($"\t\tpublic {pair.DefName}(string defname, string filename, int headerLine)");
		builder.AppendLine("\t\t\t: base(defname, filename, headerLine) {");
		foreach (var field in fields) {
			builder.AppendLine($"\t\t\tthis.{field.Name} = this.InitTypedField(\"{field.Name}\", {field.DefaultExpression}, typeof({field.TypeName}));");
		}
		builder.AppendLine("\t\t}");
		builder.AppendLine();
	}

	private static void AppendDefProperties(StringBuilder builder, IReadOnlyCollection<DefFieldSpec> fields) {
		foreach (var field in fields) {
			var propertyName = ToPascal(field.Name);
			builder.AppendLine($"\t\tpublic {field.TypeName} {propertyName} {{");
			builder.AppendLine($"\t\t\tget => ({field.TypeName}) this.{field.Name}.CurrentValue;");
			builder.AppendLine($"\t\t\tset => this.{field.Name}.CurrentValue = value;");
			builder.AppendLine("\t\t}");
			builder.AppendLine();
		}
	}

	private static void AppendDefCreateImpl(StringBuilder builder, TemplatePair pair) {
		var created = pair.Family == TemplateFamily.Thing
			? $"new {pair.InstanceName}(this)"
			: $"new {pair.InstanceName}()";
		var returnType = pair.Family == TemplateFamily.Thing ? "Thing" : "Plugin";
		builder.AppendLine($"\t\tprotected override {returnType} CreateImpl() {{");
		builder.AppendLine($"\t\t\treturn {created};");
		builder.AppendLine("\t\t}");
	}

	private static void RenderInstancePartial(StringBuilder builder, TemplatePair pair) {
		if (pair.InstanceCopyAllowed)
		{
			builder.AppendLine("\t\t[DeepCopyableClass]");
		}

		builder.AppendLine("\t[SaveableClass]");
		builder.AppendLine($"\tpublic partial class {pair.InstanceName} : {pair.InstanceBaseName} {{");
		builder.AppendLine($"\t\tpublic new {pair.DefName} TypeDef => ({pair.DefName}) base.Def;");
		builder.AppendLine();
		AppendPrimaryConstructor(builder, pair);
		AppendCopyConstructor(builder, pair, pair.CopyMembers);
		AppendDelayedCopyHelpers(builder, pair, pair.CopyMembers);
		AppendSaveMethod(builder, pair, pair.SaveLoadMembers);
		AppendLoadMethod(builder, pair, pair.SaveLoadMembers);
		AppendDelayedLoadHelpers(builder, pair.SaveLoadMembers);
		builder.AppendLine("\t}");
	}

	private static void AppendPrimaryConstructor(StringBuilder builder, TemplatePair pair) {
		if (pair.Family == TemplateFamily.Plugin) {
			builder.AppendLine("\t\t[LoadingInitializer]");
			builder.AppendLine($"\t\tpublic {pair.InstanceName}() {{");
			builder.AppendLine("\t\t}");
			builder.AppendLine();
			return;
		}

		builder.AppendLine($"\t\tpublic {pair.InstanceName}({pair.DefName} myDef) : base(myDef) {{");
		builder.AppendLine("\t\t}");
		builder.AppendLine();
	}

	private static void AppendCopyConstructor(StringBuilder builder, TemplatePair pair, IReadOnlyCollection<InstanceFieldSpec> fields) {
		if (!pair.InstanceCopyAllowed) {
			return;
		}
		builder.AppendLine("\t\t[DeepCopyImplementation]");
		builder.AppendLine($"\t\tpublic {pair.InstanceName}({pair.InstanceName} copyFrom) : base(copyFrom) {{");
		foreach (var field in fields) {
			AppendCopyAssignment(builder, field);
		}
		builder.AppendLine("\t\t}");
		builder.AppendLine();
	}

	private static void AppendCopyAssignment(StringBuilder builder, InstanceFieldSpec field) {
		MemberValueCopyRenderer.AppendAssignment(
			builder,
			field.ValueKind,
			field.Name,
			field.TypeName);
	}

	private static void AppendDelayedCopyHelpers(StringBuilder builder, TemplatePair pair, IReadOnlyCollection<InstanceFieldSpec> fields) {
		if (!pair.InstanceCopyAllowed) {
			return;
		}
		foreach (var field in fields.Where(f => MemberValueCopyRenderer.NeedsDelayed(f.ValueKind))) {
			MemberValueCopyRenderer.AppendDelayedMethod(
				builder,
				field.ValueKind,
				field.Name,
				field.TypeName);
		}
	}

	private static void AppendSaveMethod(StringBuilder builder, TemplatePair pair, IReadOnlyCollection<InstanceFieldSpec> fields) {
		if (fields.Count == 0) {
			return;
		}
		if (pair.Family == TemplateFamily.Plugin) {
			builder.AppendLine("\t\t[Save]");
		}
		builder.AppendLine("\t\tpublic override void Save(SaveStream output) {");
		foreach (var field in fields) {
			builder.AppendLine($"\t\t\tif (this.{field.Name} != {field.DefaultExpression}) output.WriteValue(\"{field.Name}\", this.{field.Name});");
		}
		builder.AppendLine("\t\t\tbase.Save(output);");
		builder.AppendLine("\t\t}");
		builder.AppendLine();
	}

	private static void AppendLoadMethod(StringBuilder builder, TemplatePair pair, IReadOnlyCollection<InstanceFieldSpec> fields) {
		if (fields.Count == 0) {
			return;
		}
		if (pair.Family == TemplateFamily.Plugin) {
			builder.AppendLine("\t\t[LoadLine]");
		}
		builder.AppendLine("\t\tpublic override void LoadLine(string filename, int line, string valueName, string valueString) {");
		builder.AppendLine("\t\t\tswitch (valueName) {");
		foreach (var field in fields) {
			AppendLoadCase(builder, field);
		}
		builder.AppendLine("\t\t\t\tdefault:");
		builder.AppendLine("\t\t\t\t\tbase.LoadLine(filename, line, valueName, valueString);");
		builder.AppendLine("\t\t\t\t\tbreak;");
		builder.AppendLine("\t\t\t}");
		builder.AppendLine("\t\t}");
		builder.AppendLine();
	}

	private static void AppendLoadCase(StringBuilder builder, InstanceFieldSpec field) {
		builder.AppendLine($"\t\t\t\tcase \"{field.Name.ToLowerInvariant()}\":");
		if (MemberValueLoadRenderer.NeedsDelayed(field.ValueKind)) {
			var methodName = "DelayedLoad_" + ToPascal(field.Name);
			builder.AppendLine($"\t\t\t\t\tObjectSaver.Load(valueString, new LoadObject(this.{methodName}), filename, line);");
		} else {
			var expression = MemberValueLoadRenderer.GetSimpleExpression(field.ValueKind, field.TypeName);
			builder.AppendLine($"\t\t\t\t\tthis.{field.Name} = {expression};");
		}
		builder.AppendLine("\t\t\t\t\tbreak;");
	}

	private static void AppendDelayedLoadHelpers(StringBuilder builder, IReadOnlyCollection<InstanceFieldSpec> fields) {
		foreach (var field in fields.Where(f => MemberValueLoadRenderer.NeedsDelayed(f.ValueKind))) {
			MemberValueLoadRenderer.AppendDelayedMethod(
				builder,
				field.ValueKind,
				field.Name,
				field.TypeName);
		}
	}

	private static string ToPascal(string name) {
		if (string.IsNullOrEmpty(name)) {
			return name;
		}
		return char.ToUpperInvariant(name[0]) + name.Substring(1);
	}
}
