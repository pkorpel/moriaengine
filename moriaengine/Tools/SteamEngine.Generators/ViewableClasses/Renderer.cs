using System.Text;
using Microsoft.CodeAnalysis.Text;

namespace SteamEngine.Generators.ViewableClasses;

/// <summary>
/// Last stage of the ViewableClass pipeline: prints the analyzer's model as C#. Members are
/// accessed directly (casts and calls, no reflection), one sealed singleton class per row
/// helper, button helper and data view.
/// </summary>
internal static class Renderer {
	/// <summary>Renders the whole ViewableClasses.g.cs file.</summary>
	internal static SourceText Render(ViewableOutput output) {
		var builder = new StringBuilder();
		// File header and the namespace the runtime looks in.
		builder.AppendLine("// <auto-generated/>");
		builder.AppendLine("#nullable disable");
		builder.AppendLine("using System;");
		builder.AppendLine("using System.Collections.Generic;");
		builder.AppendLine("using SteamEngine.CompiledScripts.Dialogs;");
		builder.AppendLine("using SteamEngine.Persistence;");
		builder.AppendLine();
		builder.AppendLine("namespace SteamEngine.CompiledScripts.Dialogs {");

		// Shared helpers first, then the views that list them.
		foreach (var fieldView in output.FieldViews) {
			AppendFieldView(builder, fieldView);
		}
		foreach (var buttonView in output.ButtonViews) {
			AppendButtonView(builder, buttonView);
		}
		foreach (var dataView in output.DataViews) {
			AppendDataView(builder, dataView, output);
		}

		builder.AppendLine("}");
		return SourceText.From(builder.ToString(), Encoding.UTF8);
	}

	/// <summary>
	/// Prints one row helper: label, type, getter, and for writable rows a setter for values
	/// and one for edit box text.
	/// </summary>
	private static void AppendFieldView(StringBuilder builder, ViewableFieldViewModel model) {
		var field = model.Field;
		var baseType = field.CanWrite ? "ReadWriteDataFieldView" : "ReadOnlyDataFieldView";
		builder.AppendLine();
		builder.AppendLine("\tpublic sealed class " + model.ClassName + " : " + baseType + " {");
		builder.AppendLine("\t\tpublic static readonly " + model.ClassName + " Instance = new " + model.ClassName + "();");
		builder.AppendLine("\t\tpublic override string GetName(object target) => " + ToLiteral(field.Label) + ";");
		builder.AppendLine("\t\tpublic override global::System.Type FieldType => typeof(" + field.FieldTypeName + ");");
		// A member row casts the target and reads or assigns the member.
		if (field.DescriptorTypeName is null) {
			var member = "((" + field.TargetTypeName + ")target)." + field.MemberName;
			builder.AppendLine("\t\tpublic override object GetValue(object target) => " + member + ";");
			builder.AppendLine("\t\tpublic override string GetStringValue(object target) => ObjectSaver.Save(" + member + ");");
			if (field.CanWrite) {
				builder.AppendLine("\t\tpublic override void SetValue(object target, object value) {");
				builder.AppendLine("\t\t\t" + member + " = (" + field.FieldTypeName + ")value;");
				builder.AppendLine("\t\t}");
				builder.AppendLine("\t\tpublic override void SetStringValue(object target, string value) {");
				builder.AppendLine("\t\t\t" + member + " = " + field.LoadExpression + ";");
				builder.AppendLine("\t\t}");
			}
		} else {
			// A descriptor row calls the descriptor's static Get/Set methods.
			var getter = field.DescriptorTypeName + "." + field.GetterMethodName + "(target)";
			builder.AppendLine("\t\tpublic override object GetValue(object target) => " + getter + ";");
			builder.AppendLine("\t\tpublic override string GetStringValue(object target) => ObjectSaver.Save(" + getter + ");");
			if (field.CanWrite) {
				builder.AppendLine("\t\tpublic override void SetValue(object target, object value) {");
				builder.AppendLine("\t\t\t" + field.DescriptorTypeName + "." + field.SetterMethodName + "(target, value);");
				builder.AppendLine("\t\t}");
				builder.AppendLine("\t\tpublic override void SetStringValue(object target, string value) {");
				builder.AppendLine("\t\t\t" + field.DescriptorTypeName + "." + field.SetterMethodName + "(target, " + field.LoadExpression + ");");
				builder.AppendLine("\t\t}");
			}
		}
		builder.AppendLine("\t}");
	}

	/// <summary>Prints one button helper: label and the call it makes.</summary>
	private static void AppendButtonView(StringBuilder builder, ViewableButtonViewModel model) {
		var button = model.Button;
		builder.AppendLine();
		builder.AppendLine("\tpublic sealed class " + model.ClassName + " : ButtonDataFieldView {");
		builder.AppendLine("\t\tpublic static readonly " + model.ClassName + " Instance = new " + model.ClassName + "();");
		builder.AppendLine("\t\tpublic override string GetName(object target) => " + ToLiteral(button.Label) + ";");
		if (button.DescriptorTypeName is null) {
			builder.AppendLine("\t\tpublic override void OnButton(object target) {");
			builder.AppendLine("\t\t\t((" + button.TargetTypeName + ")target)." + button.MethodName + "();");
			builder.AppendLine("\t\t}");
		} else {
			builder.AppendLine("\t\tpublic override void OnButton(object target) {");
			builder.AppendLine("\t\t\t" + button.DescriptorTypeName + "." + button.MethodName + "(target);");
			builder.AppendLine("\t\t}");
		}
		builder.AppendLine("\t}");
	}

	/// <summary>
	/// Prints one data view: static arrays of its row and button helpers in display order,
	/// the handled type, the headline and paging over both arrays.
	/// </summary>
	private static void AppendDataView(StringBuilder builder, ViewableDataViewModel model, ViewableOutput output) {
		builder.AppendLine();
		builder.AppendLine("\tpublic sealed class " + model.ClassName + " : ViewableClassDataView {");
		// Rows and buttons are fixed per type, so they are built once.
		builder.AppendLine("\t\tprivate static readonly IDataFieldView[] dataFields = new IDataFieldView[] {");
		foreach (var field in model.Fields) {
			builder.AppendLine("\t\t\t" + output.FieldClassNames[field.Identity] + ".Instance,");
		}
		builder.AppendLine("\t\t};");
		builder.AppendLine("\t\tprivate static readonly ButtonDataFieldView[] actionButtons = new ButtonDataFieldView[] {");
		foreach (var button in model.Buttons) {
			builder.AppendLine("\t\t\t" + output.ButtonClassNames[button.Identity] + ".Instance,");
		}
		builder.AppendLine("\t\t};");
		// IDataView members; the pages simply yield from the arrays.
		builder.AppendLine("\t\tpublic override global::System.Type HandledType => typeof(" + model.TypeName + ");");
		builder.AppendLine("\t\tpublic override string GetName(object instance) => " + ToLiteral(model.Label) + ";");
		builder.AppendLine("\t\tpublic override int GetFieldsCount(object instance) => dataFields.Length;");
		builder.AppendLine("\t\tpublic override int GetActionButtonsCount(object instance) => actionButtons.Length;");
		builder.AppendLine("\t\tpublic override IEnumerable<IDataFieldView> GetDataFieldsPage(int firstLineIndex, object target) {");
		builder.AppendLine("\t\t\tfor (var index = firstLineIndex; index >= 0 && index < dataFields.Length; index++) {");
		builder.AppendLine("\t\t\t\tyield return dataFields[index];");
		builder.AppendLine("\t\t\t}");
		builder.AppendLine("\t\t}");
		builder.AppendLine("\t\tpublic override IEnumerable<ButtonDataFieldView> GetActionButtonsPage(int firstLineIndex, object target) {");
		builder.AppendLine("\t\t\tfor (var index = firstLineIndex; index >= 0 && index < actionButtons.Length; index++) {");
		builder.AppendLine("\t\t\t\tyield return actionButtons[index];");
		builder.AppendLine("\t\t\t}");
		builder.AppendLine("\t\t}");
		builder.AppendLine("\t}");
	}

	/// <summary>Escapes text as a C# string literal.</summary>
	private static string ToLiteral(string value) {
		return Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, quote: true);
	}
}
