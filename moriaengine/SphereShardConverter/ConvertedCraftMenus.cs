using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using System.Text.RegularExpressions;
using SteamEngine.Common;

namespace SteamEngine.Converter {

	/// <summary>#962 - Erebor builds its craft menus by running scripts (cmprep_blacksmith calls metalsection(Mithril,Elven) and so
	/// on), which a line by line conversion can't do, so nothing ever reached the menus. This runs those few functions and writes
	/// the result as [CraftMenuDef]s. A container shows what went in last first, so a menu reads the other way round from its
	/// script: Copper before Mithril. That's why cm_armorset counts down.</summary>
	internal static class ConvertedCraftMenus {
		private sealed class Node {
			internal string name;
			internal string item;
			internal int circle;
			internal readonly List<Node> children = new List<Node>();
		}

		private const string MenuFolder = "systems/craftmenu";
		private const string ArmorTables = "systems/nastaveni_ceho.scp";

		private static readonly Regex functionRE = new Regex(@"^\[function\s+(?<name>\w+)\]", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
		private static readonly Regex callRE = new Regex(@"^(?<name>\w+)\s*\((?<args>.*)\)\s*$", RegexOptions.CultureInvariant);
		private static readonly Regex argvRE = new Regex(@"<argv\((?<index>\d+)\)>", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
		private static readonly Regex tableEntryRE = new Regex(@"^return\s*""?(?<value>[^""]+)""?\s*$", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);

		private static readonly Dictionary<string, List<string>> functions = new Dictionary<string, List<string>>(StringComparer.OrdinalIgnoreCase);
		private static readonly List<Node> menus = new List<Node>();
		private static Node top, level0Section, currentSection;

		public static void Write(string convertPath, string outputPath) {
			string scripts = Path.Combine(convertPath, "scripts");
			string folder = Path.Combine(scripts, MenuFolder);
			if (!Directory.Exists(folder)) {
				ConverterLogger.WriteWarning("No " + folder + ", no craft menus.");
				return;
			}
			functions.Clear();
			menus.Clear();
			string[] files = Directory.GetFiles(folder, "*.scp");
			Array.Sort(files, StringComparer.Ordinal);
			foreach (string file in files) {
				ReadFunctions(file);
			}
			ReadFunctions(Path.Combine(scripts, ArmorTables));
			foreach (string name in new List<string>(functions.Keys)) {
				if (name.StartsWith("cmprep_", StringComparison.OrdinalIgnoreCase)) {
					Run(name, new string[0]);
				}
			}

			string target = Tools.CombineMultiplePaths(outputPath, "scripts", MenuFolder, "craftmenus.def");
			Tools.EnsureDirectory(Path.GetDirectoryName(target));
			StringBuilder output = new StringBuilder("//Automatically generated by SteamEngine's converter, by running systems/craftmenu's cmprep_* functions\n");
			foreach (Node menu in menus) {
				output.Append("\n[CraftMenuDef craftmenu_").Append(SkillKey(menu.name)).Append("]\n");
				WriteChildren(menu, 0, output);
			}
			File.WriteAllText(target, output.ToString());
		}

		private static string SkillKey(string menuName) {
			return menuName.Equals("Bowcrafting", StringComparison.OrdinalIgnoreCase) ? "Bowcraft" : menuName;
		}

		private static void WriteChildren(Node parent, int depth, StringBuilder output) {
			for (int i = parent.children.Count - 1; i >= 0; i--) {
				Node child = parent.children[i];
				if (child.item != null) {
					bool defined = ConvertedItemDef.itemsByDefname.ContainsKey(child.item) || HandWrittenScripts.IsDefined(child.item);
					output.Append(defined ? "" : "//no such item: ").Append("Entry = item, ").Append(child.item).Append('\n');
				} else if (child.circle != 0) {
					output.Append("Entry = circle, ").Append(child.circle).Append('\n');
				} else {
					output.Append("Entry = section, ").Append(depth).Append(", ").Append(child.name).Append('\n');
					WriteChildren(child, depth + 1, output);
				}
			}
		}

		private static void ReadFunctions(string file) {
			List<string> body = null;
			foreach (string rawLine in File.ReadLines(file, Encoding.Latin1)) {
				string line = rawLine.Split(new[] { "//" }, 2, StringSplitOptions.None)[0].Trim();
				if (line.StartsWith("[", StringComparison.Ordinal)) {
					Match m = functionRE.Match(line);
					if (m.Success) {
						body = new List<string>();
						functions[m.Groups["name"].Value] = body;
					} else {
						body = null;
					}
				} else if ((body != null) && (line.Length > 0)) {
					body.Add(line);
				}
			}
		}

		private static string Substitute(string line, string[] args) {
			return argvRE.Replace(line, m => {
				int index = int.Parse(m.Groups["index"].Value);
				return (index < args.Length) ? args[index] : "";
			});
		}

		private static string[] Arguments(string text) {
			string[] parts = text.Split(',');
			for (int i = 0; i < parts.Length; i++) {
				parts[i] = parts[i].Trim().Trim('"');
			}
			return parts;
		}

		private static void Run(string function, string[] args) {
			foreach (string rawLine in functions[function]) {
				Match m = callRE.Match(Substitute(rawLine, args));
				if (m.Success) {
					Call(m.Groups["name"].Value, Arguments(m.Groups["args"].Value));
				}
			}
		}

		private static void Call(string name, string[] args) {
			switch (name.ToLowerInvariant()) {
				case "newtopobj":
					top = new Node { name = args[0] };
					menus.Add(top);
					level0Section = null;
					currentSection = top;
					break;
				case "cm_newsection":
					Node section = new Node { name = args[1] };
					if (args[0] == "0") {
						top.children.Add(section);
						level0Section = section;
					} else {
						level0Section.children.Add(section);
					}
					currentSection = section;
					break;
				case "cm_newitem":
					currentSection.children.Add(new Node { item = args[0] });
					break;
				case "cm_armorset":
					AddArmorSet(args[0], args[1]);
					break;
				case "scribesection":
					currentSection.children.Add(new Node { circle = int.Parse(args[0]) });
					break;
				default:
					if (functions.ContainsKey(name) && name.ToLowerInvariant().Contains("section")) {
						Run(name, args);
					}
					break;
			}
		}

		//f_platedefname and so on: a doswitch whose first return is how many pieces follow, each named after the metal
		private static void AddArmorSet(string metal, string kind) {
			List<string> names = new List<string>();
			foreach (string line in functions["f_" + kind + "defname"]) {
				Match m = tableEntryRE.Match(line);
				if (m.Success) {
					names.Add(Substitute(m.Groups["value"].Value, new[] { "", metal }));
				}
			}
			for (int piece = names.Count - 1; piece >= 1; piece--) {
				currentSection.children.Add(new Node { item = names[piece] });
			}
		}
	}
}
